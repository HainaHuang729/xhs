import assert from 'node:assert/strict';
import {swipeDirection,motionAllowed} from '../map/discovery-motion.js';
import {discoveryLayout} from '../map/discovery-layouts.js';
assert.equal(discoveryLayout('').id,'focus');
assert.equal(discoveryLayout('?look=unknown').id,'focus');
assert.equal(discoveryLayout('?look=list').id,'list');
assert.equal(swipeDirection({dx:-95,dy:4,width:346}),1,'swiping left opens the next note');
assert.equal(swipeDirection({dx:95,dy:4,width:346}),-1,'swiping right returns to the previous note');
assert.equal(swipeDirection({dx:90,dy:120,width:346}),0,'a diagonal vertical scroll must not flip a card');
assert.equal(swipeDirection({dx:-12,dy:1,velocity:-.9,width:346}),0,'a tap with slight finger movement must not flip a card');
assert.equal(swipeDirection({dx:-35,dy:2,velocity:-.7,width:346}),1,'a deliberate short flick can advance');
assert.equal(swipeDirection({dx:-35,dy:2,velocity:.7,width:346}),0,'a gesture returning toward its origin should settle back');
assert.equal(swipeDirection({dx:-58,dy:3,width:284}),1,'a phone-width card has a reachable swipe threshold');
assert.equal(swipeDirection({dx:-58,dy:3,width:1000}),0,'a small accidental drag on a desktop should settle back');
assert.equal(swipeDirection({dx:-500,dy:0,width:0}),0,'a hidden stage must not advance');
globalThis.matchMedia=()=>({matches:true});
assert.equal(motionAllowed({type:'pointerup'}),false,'reduced motion also applies to finger gestures');
globalThis.matchMedia=()=>({matches:false});
assert.equal(motionAllowed({type:'keydown'}),false,'keyboard browsing changes content immediately');
assert.equal(motionAllowed({type:'click',detail:0}),false,'keyboard-activated buttons change content immediately');
assert.equal(motionAllowed({type:'click',detail:1}),true);
delete globalThis.matchMedia;
console.log('单卡漫游检查通过：默认版式、左右翻页、纵向滚动保护、轻触保护、快速轻扫和回位判断。');
